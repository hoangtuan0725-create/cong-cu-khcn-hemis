import re, urllib.parse, html
src = open('tool.js', encoding='utf-8').read()
src = "\n".join(l for l in src.splitlines() if not l.strip().startswith('/*'))
src = re.sub(r'\n\s+', '\n', src).strip()
bm = 'javascript:' + urllib.parse.quote(src, safe="()'!*~-_.")
open('bookmarklet.txt','w').write(bm)
page = open('installer_template.html', encoding='utf-8').read()
page = page.replace('%%BM_ATTR%%', html.escape(bm, quote=True)).replace('%%BM_TEXT%%', html.escape(bm))
open('/mnt/user-data/outputs/Cài đặt công cụ đẩy HEMIS.html','w',encoding='utf-8').write(page)
print(len(bm))
